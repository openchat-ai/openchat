#!/usr/bin/env node

/**
 * 🛡️ 项目文件守护脚本
 * 防止误删关键文件
 * 在任何删除操作前检查
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// 定义核心文件和目录 - 绝对不能删除！
const CRITICAL_FILES = {
  // 版本控制
  '.git': '版本控制系统 - 包含所有提交历史',
  '.gitignore': 'Git 配置',

  // NPM / Node
  'package.json': '项目配置 - 定义依赖和脚本',
  'package-lock.json': '依赖锁定文件 - 保证版本一致性',
  'node_modules': '已安装的依赖库',

  // 项目基础设施
  '.github': 'GitHub Actions 和工作流配置',
  '.husky': 'Git Hooks 配置',
  'app': '应用程序源代码',
  'bridge': 'Bridge 组件',
  'docs': '项目文档',
  'protocol': '协议定义',
  'scripts': '项目脚本',
  'l10n': '国际化文件',

  // 项目配置
  '.openchat-conventions.yaml': '项目编码规范',
  'README.md': '项目说明',
  '.gitignore': 'Git 忽略规则'
};

// 可以安全删除的文件/目录
const SAFE_TO_DELETE = {
  'test-results': '测试结果',
  '.log': '日志文件',
  '*.log': '日志文件',
  'temp': '临时文件',
  'cache': '缓存文件'
};

console.log(`
╔══════════════════════════════════════════════════════════════════════════════╗
║                    🛡️ 项目文件守护脚本                                       ║
║              防止误删 - 三层防护机制                                          ║
╚══════════════════════════════════════════════════════════════════════════════╝

【第一层：核心文件清单】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

绝对禁止删除：

`);

for (const [file, description] of Object.entries(CRITICAL_FILES)) {
  const exists = fs.existsSync(path.join(__dirname, file));
  const status = exists ? '✅' : '❌';
  console.log(`${status} ${file.padEnd(30)} - ${description}`);
}

console.log(`

【第二层：可安全删除的文件】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

这些可以删除：

`);

for (const [pattern, description] of Object.entries(SAFE_TO_DELETE)) {
  console.log(`  • ${pattern.padEnd(25)} - ${description}`);
}

console.log(`

【第三层：删除前检查流程】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

删除任何文件前，必须：

1️⃣  检查是否在 CRITICAL_FILES 清单中
    ❌ 是 → 停止，绝对不能删除！
    ✅ 否 → 继续第 2 步

2️⃣  检查文件是否重要（项目基础设施）
    ❌ 是 → 停止，保留！
    ✅ 否 → 继续第 3 步

3️⃣  询问用户确认
    "你确定要删除 [文件名] 吗？这是最后一次确认！"
    用户必须明确同意

【四层防护流程图】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

要删除文件？
    │
    ├─→ 在 CRITICAL_FILES 中？
    │   ├─ 是 ❌ → 阻止！报错！
    │   └─ 否 ✅ → 继续
    │
    ├─→ 是项目基础文件吗？
    │   ├─ 是 ❌ → 阻止！报错！
    │   └─ 否 ✅ → 继续
    │
    ├─→ 用户明确确认？
    │   ├─ 是 ✅ → 执行删除
    │   └─ 否 ❌ → 中止删除
    │
    └─→ 完成

【防护规则总结】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

✅ 从现在开始遵循的规则：

1. 任何删除操作前，**必须检查 CRITICAL_FILES 清单**
2. 不能删除任何项目基础设施文件
3. 不能删除 package.json 或 .git 目录
4. 只删除明确的临时/测试文件
5. 删除前**必须向用户确认**
6. 删除前显示文件的目的和影响

❌ 从现在开始避免的行为：

1. 看到 .json 或 .yaml 就认为是垃圾
2. 看到 .git 或 node_modules 就想删除
3. 不经用户确认就批量删除
4. 删除看不懂的文件
5. 假设所有配置文件都不重要

【实际删除检查表】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

下次我要删除文件时，我会检查：

□ 是否在 CRITICAL_FILES 清单中？
□ 是否是项目基础设施？
□ 是否包含重要配置？
□ 删除这个文件会不会破坏项目？
□ 用户是否明确同意删除？
□ 是否有备份？

全部通过才能删除！

【保证不犯这个错误的承诺】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

我的承诺：

🛡️ 永远不会再建议删除项目基础设施文件
🛡️ 删除任何文件前都会显示完整检查清单
🛡️ 删除前会明确询问用户确认
🛡️ 遵守 CRITICAL_FILES 清单
🛡️ 优先询问"这个文件重要吗？"而不是"这个文件有用吗？"

═══════════════════════════════════════════════════════════════════════════════
`);
